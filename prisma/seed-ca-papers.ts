// ─── MAIN ────────────────────────────────────────────────────────────────────

async function main() {
  console.log('🌐 Seeding 5 Current Affairs papers...\n')

  const { data: subs } = await supabase.from('subjects').select('*')
  const S: Record<string, any> = {}
  subs!.forEach((s: any) => { S[s.code] = s })

  const { data: tops } = await supabase.from('topics').select('*')
  const T: Record<string, any> = {}
  tops!.forEach((t: any) => { T[t.name_hi] = t })

  // Use GK subject as the base subject for CA questions (closest match)
  const gkSubjectId = S['GK']?.id
  const caTopicId = T['करंट अफेयर्स']?.id ?? null

  const buildQs = (qs: Q[]) =>
    qs.map(([textHi, a, b, c, d, ans]) => ({
      text_hi: textHi,
      option_a: a, option_b: b, option_c: c, option_d: d,
      correct: ans,
      explanation: ({ A: a, B: b, C: c, D: d } as Record<string,string>)[ans],
      subject_id: gkSubjectId,
      topic_id: caTopicId,
      difficulty: 'MEDIUM' as const,
      source: 'MP Patwari 2026 Current Affairs',
      is_active: true,
    }))

  const insertBatch = async (rows: any[]) => {
    const results: any[] = []
    for (let i = 0; i < rows.length; i += 25) {
      const { data, error } = await supabase.from('questions').insert(rows.slice(i, i + 25)).select()
      if (error) { console.error('Insert error:', error.message); continue }
      results.push(...(data ?? []))
    }
    return results
  }

  const createCATest = async (
    titleEn: string, titleHi: string, paperNum: number, qs: any[]
  ) => {
    const { data: test, error } = await supabase.from('mock_tests').insert({
      title: titleEn,
      title_hi: titleHi,
      description: `MP Patwari 2026 के लिए ${titleHi}। 2024-26 के महत्वपूर्ण करंट अफेयर्स पर आधारित।`,
      type: 'CURRENT_AFFAIRS',
      total_questions: qs.length,
      total_marks: qs.length,
      duration: 25,
      negative_marks: 0.25,
      is_published: true,
      subject_id: null,
      sort_order: 200 + paperNum,
    }).select().single()
    if (error || !test) { console.error('Test create error:', error?.message); return }
    const tqs = qs.map((q: any, i: number) => ({ test_id: test.id, question_id: q.id, sort_order: i + 1 }))
    await supabase.from('test_questions').insert(tqs)
    console.log(`  ✓ Created: ${titleHi}`)
  }

  const papers = [
    { n: 1, qs: caP1, en: 'Current Affairs Paper 1 - MP Budget & Schemes 2025-26', hi: 'करंट अफेयर्स पेपर 1 - MP बजट एवं योजनाएं' },
    { n: 2, qs: caP2, en: 'Current Affairs Paper 2 - National Current Affairs 2025-26', hi: 'करंट अफेयर्स पेपर 2 - राष्ट्रीय घटनाएं 2025-26' },
    { n: 3, qs: caP3, en: 'Current Affairs Paper 3 - Science, Technology & Space', hi: 'करंट अफेयर्स पेपर 3 - विज्ञान, तकनीक एवं अंतरिक्ष' },
    { n: 4, qs: caP4, en: 'Current Affairs Paper 4 - Sports, Awards & Appointments', hi: 'करंट अफेयर्स पेपर 4 - खेल, पुरस्कार एवं नियुक्तियां' },
    { n: 5, qs: caP5, en: 'Current Affairs Paper 5 - International Events & India', hi: 'करंट अफेयर्स पेपर 5 - अंतर्राष्ट्रीय घटनाएं एवं भारत' },
  ]

  for (const p of papers) {
    console.log(`\n📰 Processing: ${p.hi}`)
    const insertedQs = await insertBatch(buildQs(p.qs))
    await createCATest(p.en, p.hi, p.n, insertedQs)
  }

  console.log('\n✅ Done! 5 Current Affairs papers seeded (100 questions total).')
}

main().catch(console.error)
